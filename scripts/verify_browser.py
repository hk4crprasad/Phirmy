from playwright.sync_api import sync_playwright,expect
from pathlib import Path
import uuid,json,os
root=Path(__file__).resolve().parents[1]/'artifacts';root.mkdir(exist_ok=True)
origin=os.environ.get('BROWSER_TEST_ORIGIN','http://127.0.0.1:3100')
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 page=browser.new_page(viewport={'width':1440,'height':1000})
 page.set_default_timeout(60000)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(origin+'/signin');page.wait_for_load_state('networkidle')
 page.get_by_role('button',name='Create a workspace',exact=True).click()
 page.get_by_label('Your name').fill('Studio QA')
 page.get_by_label('Work email').fill('browser-'+uuid.uuid4().hex[:8]+'@example.test')
 page.get_by_label('Password',exact=True).fill('Local-QA-Password-2026')
 page.get_by_label('Workspace name').fill('Palsona Voice · QA')
 page.get_by_role('button',name='Create workspace',exact=True).click()
 page.wait_for_url('**/app');page.wait_for_load_state('networkidle')
 expect(page.get_by_role('heading',name='A little more connected, Studio.')).to_be_visible()
 page.get_by_role('button',name='Load sample workspace').click()
 expect(page.get_by_role('link',name='Gift studio assistant')).to_be_visible(timeout=60000)
 page.screenshot(path=str(root/'dashboard.png'),full_page=True)
 page.get_by_role('link',name='Knowledge',exact=True).click()
 page.get_by_role('link',name='Gift studio · sample knowledge').click()
