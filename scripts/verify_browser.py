 page.get_by_role('button',name='Retrieve sources').click()
 expect(page.get_by_text('Source passages found',exact=False)).to_be_visible(timeout=60000)
 page.screenshot(path=str(root/'knowledge.png'),full_page=True)
 page.get_by_role('link',name='Voice lab',exact=True).click()
 page.get_by_role('button',name='Start simulation',exact=True).click()
 expect(page.get_by_text('Hello, this is your AI support assistant. How can I help?',exact=True)).to_be_visible(timeout=60000)
 page.get_by_label('Voice lab text turn').fill('What is the engraving character limit?')
 page.get_by_role('button',name='Send test turn').click()
 expect(page.get_by_text('From the connected source:',exact=False)).to_be_visible(timeout=60000)
 page.get_by_label('Voice lab text turn').fill('Please create a support ticket for a follow-up.')
 page.get_by_role('button',name='Send test turn').click()
 expect(page.get_by_text('Confirm request',exact=False)).to_be_visible(timeout=60000)
 page.wait_for_timeout(250)
 page.get_by_label('Voice lab text turn').fill('Confirm request')
 page.get_by_role('button',name='Send test turn').click()
 expect(page.get_by_text("I've recorded your request as a support ticket.",exact=False)).to_be_visible(timeout=60000)
 page.screenshot(path=str(root/'voice-lab.png'),full_page=True)
 page.get_by_role('button',name='End session',exact=True).click()
 expect(page.get_by_role('button',name='Start simulation',exact=True)).to_be_visible(timeout=60000)
 page.get_by_role('link',name='Inbox',exact=True).click()
 expect(page.get_by_text('Voice follow-up request',exact=True)).to_be_visible(timeout=60000)
 page.get_by_role('link',name='Chat widget',exact=True).click()
 page.wait_for_load_state('networkidle')
 page.get_by_label('Chat message',exact=True).fill('What is the cufflinks price?')
 page.get_by_role('button',name='Send chat message').click()
 expect(page.get_by_text('Personalised cufflinks is INR 999.',exact=False)).to_be_visible(timeout=60000)
 page.screenshot(path=str(root/'widget.png'),full_page=True)
 page.set_viewport_size({'width':390,'height':844})
 page.screenshot(path=str(root/'mobile-widget.png'),full_page=True)
 assert not errors,errors
 result={'signup':'passed','knowledge_retrieval':'passed','browser_simulation':'passed','durable_ticket':'passed','catalog_chat':'passed','page_errors':errors}
 (root/'browser-results.json').write_text(json.dumps(result,indent=2))
 print(json.dumps(result))
 browser.close()
