"""Browser acceptance of first-value handoff and custom-tool setup; no provider keys."""
import json,uuid
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

expect.set_options(timeout=60000)
ART=Path(__file__).resolve().parents[1]/'artifacts'
ART.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    page.set_default_timeout(90000)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3100')
    page.get_by_label('Your website',exact=True).fill('https://palsona.in')
    page.get_by_role('button',name='Try my website').click()
    expect(page.get_by_text('Your website, understood.',exact=True)).to_be_visible()
    page.get_by_role('link',name='Keep my assistant').click()
    page.get_by_label('Your name').fill('Platform QA')
    page.get_by_label('Work email').fill('agent-platform-'+uuid.uuid4().hex[:10]+'@example.test')
    page.get_by_label('Password',exact=True).fill('Local-QA-Password-2026')
    page.get_by_label('Workspace name').fill('Palsona · platform QA')
    page.get_by_role('button',name='Create workspace',exact=True).click()
    page.wait_for_url('**/app/agents/*')
    page.wait_for_load_state('networkidle')
    agent_name=page.get_by_role('heading',level=1).inner_text()
    expect(page.locator('.badge.published').first).to_be_visible()
    page.get_by_role('link',name='Tools',exact=True).click()
    page.get_by_role('button',name='Add HTTP tool').click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_text('Import a cURL request',exact=True).click()
    dialog.get_by_label('Request',exact=True).fill('''curl -X POST https://example.com/orders -H 'Authorization: Bearer qa-example-private-token' -d '{"order_id":"{{order_id}}"}' ''')
    dialog.get_by_role('button',name='Parse request').click()
    expect(dialog.get_by_label('Public endpoint URL')).to_have_value('https://example.com/orders')
    dialog.get_by_label('Tool name',exact=True).fill('lookup_order')
    dialog.get_by_label('When should the agent use this tool?').fill('Look up an order when the customer asks for its status.')
    dialog.get_by_label('Optional mock response · JSON').fill('{"status":"QA example only"}')
    dialog.get_by_role('button',name='Save tool',exact=True).click()
    expect(dialog.get_by_role('button',name='Save agent access')).to_be_visible()
    dialog.get_by_role('checkbox').first.check()
    dialog.get_by_role('button',name='Save agent access').click()
    expect(page.locator('.toast')).to_contain_text('Agent drafts updated')
    dialog.get_by_role('button',name='Test',exact=True).click()
    dialog.get_by_label('Test arguments · JSON').fill('{"order_id":"ORD-QA"}')
    dialog.get_by_role('button',name='Use mock').click()
    expect(dialog.locator('pre')).to_contain_text('QA example only')
    expect(dialog.locator('pre')).to_contain_text('"external_request": false')
    page.screenshot(path=str(ART/'tool-studio-desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth')
    page.screenshot(path=str(ART/'tool-studio-mobile.png'),full_page=True)
    dialog.get_by_role('button',name='Close dialog').click()
    page.set_viewport_size({'width':1440,'height':1000})
    page.get_by_role('link',name='Models',exact=True).click()
    expect(page.get_by_role('heading',name='Your model. Your voice agent.')).to_be_visible()
    page.get_by_role('button',name='Add model',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('API protocol').select_option('responses')
    expect(dialog.get_by_label('Documented output cap')).to_have_value('max_output_tokens')
    expect(dialog.get_by_label('Temperature · optional')).to_have_value('')
    page.screenshot(path=str(ART/'model-studio.png'),full_page=True)
    dialog.get_by_role('button',name='Close dialog').click()
    page.get_by_role('link',name='Team',exact=True).click()
    page.get_by_role('button',name='Invite teammate').click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('Work email').fill('invited-'+uuid.uuid4().hex[:10]+'@example.test')
    dialog.get_by_role('button',name='Create invitation',exact=True).click()
    expect(page.get_by_role('dialog',name='Their next step starts here')).to_be_visible()
    expect(page.get_by_role('dialog').locator('.code')).to_contain_text('/invite?token=')
    page.get_by_role('button',name='Close dialog').click()
    for route in ['operations','campaigns','integrations','numbers','billing','developers']:
        page.goto('http://127.0.0.1:3100/app/'+route)
        expect(page.locator('main h1')).to_be_visible()
        expect(page.locator('main [role="alert"]')).to_have_count(0)
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'),route
