    page.goto('http://127.0.0.1:3100/docs')
    expect(page.get_by_role('heading',name='Bring your model')).to_be_visible()
    expect(page.locator('#events')).to_contain_text('X-Studio-Signature')
    page.screenshot(path=str(ART/'developer-docs.png'),full_page=True)
    assert not errors,errors
    result={'preview_to_published_agent':'passed','curl_import':'passed','write_only_headers':'backend-verified','draft_tool_access':'passed','mock_without_request':'passed','model_protocol_selection':'passed','invitation_link':'passed','workspace_navigation':'passed','mobile_overflow':'none','developer_docs':'passed','page_errors':errors}
    (ART/'agent-platform-results.json').write_text(json.dumps(result,indent=2));print(json.dumps(result));browser.close()
